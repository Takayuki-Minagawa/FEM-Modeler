import type { ProjectIR } from '@/core/ir/types';
import { escapeMarkdownInline, markdownTableRow, sanitizeArtifactName } from '@/export/shared/artifact-sanitization';
import { buildConditionReportTables, buildReproductionReportTables, REPORT_UNIT_BASIS, type ReportTable } from './report-data';

function tableLines(table: ReportTable): string[] {
  return [`## ${table.title}`, '', markdownTableRow(table.columns), markdownTableRow(table.columns.map(() => '---')), ...table.rows.map(markdownTableRow), ''];
}

function header(ir: ProjectIR, kind: string): string[] {
  return [
    `# ${escapeMarkdownInline(ir.meta.project_name)}`, '',
    `- **Report**: ${kind}`,
    `- **Project ID**: ${escapeMarkdownInline(ir.meta.project_id)}`,
    `- **Domain**: ${escapeMarkdownInline(ir.meta.domain_type)}`,
    `- **Report units**: ${REPORT_UNIT_BASIS}`,
    `- **Display preference only**: ${escapeMarkdownInline(ir.units.system_name)} (does not change report values)`,
    '- **Viscosity**: dynamic viscosity μ [Pa·s]; kinematic viscosity ν [m²/s]; ν = μ / ρ with density ρ [kg/m³]',
    `- **Created**: ${escapeMarkdownInline(ir.meta.created_at)}`,
    `- **Updated**: ${escapeMarkdownInline(ir.meta.updated_at)}`,
    `- **Model revision**: ${ir.validation.model_revision}`, '',
  ];
}

function geometryLines(ir: ProjectIR): string[] {
  return [
    '## Geometry', `- Bodies: ${ir.geometry.bodies.length}`, `- Faces: ${ir.geometry.faces.length}`,
    `- Named Selections: ${ir.named_selections.length}`, '',
    markdownTableRow(['Body', 'ID', 'Category', 'Shape']), markdownTableRow(['---', '---', '---', '---']),
    ...ir.geometry.bodies.map((body) => markdownTableRow([body.name, body.id, body.category, String(body.metadata.shapeType ?? '—')])), '',
  ];
}

function validationLines(ir: ProjectIR): string[] {
  const validation = ir.validation;
  const state = !validation.last_run_at ? 'Not run' : validation.validated_revision !== validation.model_revision ? 'Inputs changed after validation' : validation.context ? 'Case and solver validation' : 'Common validation';
  const context = validation.context;
  return [
    '## Validation', `- State: ${state}`,
    `- Run at: ${escapeMarkdownInline(validation.last_run_at || '—')}`,
    `- Validated revision: ${validation.validated_revision}`,
    `- Case: ${escapeMarkdownInline(context?.analysis_case_id ?? 'all / common')}`,
    `- Solver: ${escapeMarkdownInline(context?.solver_target ?? 'common')}`,
    `- Input fingerprint: ${escapeMarkdownInline(context?.input_fingerprint ?? '—')}`,
    `- Errors: ${validation.summary.error_count}`, `- Warnings: ${validation.summary.warning_count}`, `- Info: ${validation.summary.info_count}`, '',
    markdownTableRow(['Severity', 'Code', 'Target', 'Message', 'Suggested fix']), markdownTableRow(['---', '---', '---', '---', '---']),
    ...validation.items.map((item) => markdownTableRow([item.severity, item.code, item.target_ref, item.message, item.suggested_fix])), '',
  ];
}

export function exportMarkdownSummary(ir: ProjectIR): string {
  return [
    ...header(ir, 'Simple input summary'),
    'For exact geometry, assignments, mesh controls, case participation and solver options, export the reproduction report.', '',
    ...geometryLines(ir),
    ...buildConditionReportTables(ir).flatMap(tableLines),
    ...tableLines(buildReproductionReportTables(ir).find((table) => table.title === 'Solver Targets')!),
    ...validationLines(ir), '---', '*Generated by FEM Modeler*',
  ].join('\n');
}

export function exportMarkdownReport(ir: ProjectIR): string {
  // Native projects remain loadable. Binary assets are referenced by hash and
  // restored from a companion bundle, so reports do not duplicate large payloads.
  const inputSnapshot = { ...ir, results: [], convergence_studies: [], audit_trail: [],
    assets: ir.assets.map((asset) => ({ ...asset, data: undefined,
      cad_source: asset.cad_source ? { ...asset.cad_source, data: undefined } : undefined })),
  };
  const snapshot = JSON.stringify(inputSnapshot, null, 2);
  let longestFence = 2;
  for (const match of snapshot.matchAll(/`+/g)) longestFence = Math.max(longestFence, match[0].length);
  const fence = '`'.repeat(longestFence + 1);
  return [
    ...header(ir, 'Reproduction report'),
    'All numerical input values retain their stored precision. The tables explain quantities and participation; the input snapshot preserves complete geometry parameters, references and solver options.',
    'Geometry coordinates and dimensions use m; areas use m²; section inertias use m⁴; geometry rotations use deg. Dimensionless values and direction vectors use 1.',
    'For imported CAD/STL, retain the companion .fem.zip bundle: asset references and hashes below do not contain the binary geometry.', '',
    ...geometryLines(ir), ...buildConditionReportTables(ir).flatMap(tableLines), ...buildReproductionReportTables(ir).flatMap(tableLines),
    ...validationLines(ir),
    '## Project input snapshot', '',
    ir.assets.length > 0
      ? 'Reference snapshot: binary asset payloads are omitted, so this JSON cannot be loaded by itself. Open the companion .fem.zip bundle to restore the complete inputs; asset IDs and hashes below identify the required geometry.'
      : 'Copy this JSON to a .fem.json file to restore the native inputs.',
    'Results, convergence studies and audit history are omitted. Values are canonical SI even when the saved display preference is mm.', '',
    `${fence}json`, snapshot, fence, '', '---', '*Generated by FEM Modeler*',
  ].join('\n');
}

function downloadMarkdown(ir: ProjectIR, full: boolean): { fileName: string; bytes: number } {
  const text = full ? exportMarkdownReport(ir) : exportMarkdownSummary(ir);
  const blob = new Blob([text], { type: 'text/markdown;charset=utf-8' });
  const fileName = `${sanitizeArtifactName(ir.meta.project_name, 'project')}_${full ? 'report' : 'summary'}.md`;
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  a.click();
  URL.revokeObjectURL(url);
  return { fileName, bytes: blob.size };
}

export function downloadMarkdownSummary(ir: ProjectIR): { fileName: string; bytes: number } {
  return downloadMarkdown(ir, false);
}

export function downloadMarkdownReport(ir: ProjectIR): { fileName: string; bytes: number } {
  return downloadMarkdown(ir, true);
}
